const PatronDef* PatronPowers::Find(const std::string& patron)
{
	for (const PatronDef& def : kPatrons)
	{
		if (patron == def.patron)
		{
			return &def;
		}
	}

	return nullptr;
}

const SkillDef& PatronPowers::Skill(const PatronDef& def, SkillSlot slot)
{
	return (slot == SkillSlot::Ultimate) ? def.ultimate : def.basic;
}

const char* PatronPowers::KeyName(SkillSlot slot)
{
	return (slot == SkillSlot::Ultimate) ? "R" : "Q";
}
